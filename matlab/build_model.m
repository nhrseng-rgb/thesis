function model = build_model(destination)
% Aggregate swing/governor/GFM demonstration, not a multimachine RMS/EMT model.
if nargin < 1, destination = fileparts(mfilename('fullpath')); end
model = 'fig31_frequency_demo';
if bdIsLoaded(model), close_system(model,0); end
new_system(model);
set_param(model,'SolverType','Fixed-step','Solver','ode4', ...
    'FixedStep','p.dt','StopTime','p.stop_s','ReturnWorkspaceOutputs','on');
add_block('simulink/Sources/Step',[model '/Contingency'], ...
    'Time','p.event_s','Before','0','After','p.loss_mw/p.load_mw','Position',[30 220 80 250]);
add_block('simulink/Math Operations/Sum',[model '/Power balance'], ...
    'Inputs','++--','Position',[420 90 450 180]);
add_block('simulink/Math Operations/Gain',[model '/Inverse inertia'], ...
    'Gain','60/(2*(p.h_s+p.virtual_h_s*p.capacity_mw/p.load_mw))', ...
    'Position',[490 115 600 155]);
add_block('simulink/Continuous/Integrator',[model '/Frequency deviation'], ...
    'InitialCondition','0','Position',[640 115 680 155]);
add_block('simulink/Math Operations/Gain',[model '/Load damping'], ...
    'Gain','p.damping','Position',[720 270 800 310]);
add_block('simulink/Math Operations/Gain',[model '/Governor droop'], ...
    'Gain','-p.governor_gain','Position',[45 20 150 60]);
add_block('simulink/Continuous/Transfer Fcn',[model '/Governor response'], ...
    'Numerator','[1]','Denominator','[p.governor_tau 1]','Position',[210 20 340 60]);
add_block('simulink/Math Operations/Gain',[model '/GFM droop'], ...
    'Gain','-p.bess_gain*p.capacity_mw/p.load_mw','Position',[30 100 170 140]);
add_block('simulink/Discontinuities/Saturation',[model '/BESS power limit'], ...
    'UpperLimit','p.capacity_mw/p.load_mw','LowerLimit','-p.capacity_mw/p.load_mw', ...
    'Position',[205 100 250 140]);
add_block('simulink/Continuous/Transfer Fcn',[model '/BESS response'], ...
    'Numerator','[1]','Denominator','[p.bess_tau 1]','Position',[285 100 380 140]);
add_block('simulink/Sources/Constant',[model '/Nominal Hz'], ...
    'Value','60','Position',[730 35 775 65]);
add_block('simulink/Math Operations/Sum',[model '/Frequency Hz'], ...
    'Inputs','++','Position',[830 110 855 150]);
add_block('simulink/Sinks/To Workspace',[model '/Frequency record'], ...
    'VariableName','frequency','SaveFormat','Timeseries','Position',[920 110 1040 150]);
add_block('simulink/Math Operations/Gain',[model '/BESS MW'], ...
    'Gain','p.load_mw','Position',[490 360 580 400]);
add_block('simulink/Sinks/To Workspace',[model '/Power record'], ...
    'VariableName','bess_power','SaveFormat','Timeseries','Position',[650 360 770 400]);
add_block('simulink/Sinks/Scope',[model '/Frequency scope'],'Position',[920 190 960 230]);
links = {'Contingency/1','Power balance/3'; 'Governor droop/1','Governor response/1';
    'Governor response/1','Power balance/1'; 'GFM droop/1','BESS power limit/1';
    'BESS power limit/1','BESS response/1'; 'BESS response/1','Power balance/2';
    'Power balance/1','Inverse inertia/1'; 'Inverse inertia/1','Frequency deviation/1';
    'Frequency deviation/1','Load damping/1'; 'Load damping/1','Power balance/4';
    'Frequency deviation/1','Governor droop/1'; 'Frequency deviation/1','GFM droop/1';
    'Frequency deviation/1','Frequency Hz/1'; 'Nominal Hz/1','Frequency Hz/2';
    'Frequency Hz/1','Frequency record/1'; 'Frequency Hz/1','Frequency scope/1';
    'BESS response/1','BESS MW/1'; 'BESS MW/1','Power record/1'};
for i=1:size(links,1), add_line(model,links{i,1},links{i,2},'autorouting','on'); end
note = Simulink.Annotation(model, ...
    'DEMONSTRATION ONLY: aggregate frequency model. No nodal modes, faults, Q control, gSCR or EMT validation.');
note.Position = [30 450 1000 490];
save_system(model,fullfile(destination,[model '.slx']));
end
